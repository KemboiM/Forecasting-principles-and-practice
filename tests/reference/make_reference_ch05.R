# R reference values for tests/python/test_ch05.py (every Chapter 5 model)
suppressPackageStartupMessages({library(fpp2); library(jsonlite)})
fcl <- function(f) list(mean = as.numeric(f$mean), lo80 = as.numeric(f$lower[, 1]), hi80 = as.numeric(f$upper[, 1]),
                        lo95 = as.numeric(f$lower[, 2]), hi95 = as.numeric(f$upper[, 2]))
ref <- list()
fit.consMR <- tslm(Consumption ~ Income + Production + Unemployment + Savings, data = uschange)
ref$consMR_coef <- unname(coef(fit.consMR))
ref$consMR_CV <- unname(CV(fit.consMR))
ref$consMR_bg8 <- unname(lmtest::bgtest(fit.consMR, order = 8)$statistic)
preds <- c("Income", "Production", "Savings", "Unemployment")
grid <- expand.grid(rep(list(0:1), 4))
ref$subsets_AICc <- unname(apply(grid, 1, function(g) {
  rhs <- if (sum(g) == 0) "1" else paste(preds[g == 1], collapse = " + ")
  CV(tslm(as.formula(paste("Consumption ~", rhs)), data = uschange))["AICc"] }))
beer2 <- window(ausbeer, start = 1992)
fit.beer <- tslm(beer2 ~ trend + season)
ref$beer_coef <- unname(coef(fit.beer)); ref$beer_fc <- fcl(forecast(fit.beer))
ref$beer_fourier_coef <- unname(coef(tslm(beer2 ~ trend + fourier(beer2, K = 2))))
ref$easter_ausbeer <- as.numeric(easter(ausbeer))
ref$easter_a10 <- as.numeric(easter(a10))
fit.best <- tslm(Consumption ~ Income + Savings + Unemployment, data = uschange)
ref$scen_up <- fcl(forecast(fit.best, newdata = data.frame(Income = rep(1, 4), Savings = rep(0.5, 4), Unemployment = rep(0, 4))))
fit.cons <- tslm(Consumption ~ Income, data = uschange)
ref$cons_ave <- fcl(forecast(fit.cons, newdata = data.frame(Income = rep(mean(uschange[, "Income"]), 4))))
h <- 10
ref$mar_lin <- fcl(forecast(tslm(marathon ~ trend), h = h))
ref$mar_exp <- fcl(forecast(tslm(marathon ~ trend, lambda = 0), h = h))
t <- time(marathon); tb1 <- ts(pmax(0, t - 1940), start = 1897); tb2 <- ts(pmax(0, t - 1980), start = 1897)
nd <- data.frame(t = t[length(t)] + seq(h), tb1 = tb1[length(tb1)] + seq(h), tb2 = tb2[length(tb2)] + seq(h))
ref$mar_pw <- fcl(forecast(tslm(marathon ~ t + tb1 + tb2), newdata = nd))
ref$mar_spline <- fcl(forecast(tslm(marathon ~ t + I(t^2) + I(t^3) + I(tb1^3) + I(tb2^3)), newdata = nd))
ref$mar_splinef_mle <- fcl(splinef(marathon, lambda = 0, method = "mle", h = h))
ref$mar_splinef_gcv <- fcl(splinef(marathon, lambda = 0, h = h))
sb <- Seatbelts
ref$seatbelt_coef <- unname(coef(tslm(sb[, "drivers"] ~ trend + season + sb[, "law"])))
ref$spurious_coef <- unname(coef(tslm(window(ausair, end = 2011) ~ guinearice)))
ref$spurious_bg <- unname(lmtest::bgtest(tslm(window(ausair, end = 2011) ~ guinearice), order = 8)$statistic)
adv <- cbind(insurance[, "TV.advert"], stats::lag(insurance[, "TV.advert"], -1), stats::lag(insurance[, "TV.advert"], -2))[1:40, ]
ref$lags_coef <- unname(coef(lm(insurance[, "Quotes"] ~ adv)))
# exercises
daily20 <- head(elecdaily, 20)
ref$ex1 <- fcl(forecast(tslm(Demand ~ Temperature, data = daily20), newdata = data.frame(Temperature = c(15, 35))))
ref$ex2 <- fcl(forecast(tslm(mens400 ~ trend), h = 1))
surf <- ts(as.numeric(cycle(fancy) == 3 & time(fancy) >= 1988), start = 1987, frequency = 12)
fit.fancy <- tslm(log(fancy) ~ trend + season + surf)
ref$ex5_coef <- unname(coef(fit.fancy))
ref$ex5_fc <- fcl(forecast(fit.fancy, newdata = data.frame(surf = rep(c(0, 0, 1, rep(0, 9)), 3))))
ref$ex5_bg24 <- unname(lmtest::bgtest(fit.fancy, order = 24)$statistic)
gas <- window(gasoline, end = 2005)
ref$ex6_AICc <- sapply(1:26, function(K) { X <- fourier(gas, K = K); unname(CV(tslm(gas ~ trend + X))["AICc"]) })
X12 <- fourier(gas, K = 12)
ref$ex6_fc <- fcl(forecast(tslm(gas ~ trend + X12), newdata = data.frame(X12 = I(fourier(gas, K = 12, h = 52)))))
th <- time(huron); t15 <- pmax(0, th - 1915)
ref$ex7_lin <- fcl(forecast(tslm(huron ~ trend), h = 8))
ref$ex7_pw <- fcl(forecast(tslm(huron ~ th + t15), newdata = data.frame(th = 1973:1980, t15 = 1973:1980 - 1915)))
write_json(ref, "tests/reference/ch05_reference.json", digits = 12, auto_unbox = TRUE, pretty = TRUE)
