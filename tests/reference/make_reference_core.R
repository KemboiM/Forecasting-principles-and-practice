# Generates R reference numbers used by tests/python/test_fpp_core.py to prove that
# the Python helpers in python/fpp.py reproduce forecast-package results exactly.
# Run from project root:  Rscript tests/reference/make_reference_core.R
suppressPackageStartupMessages({library(fpp2); library(jsonlite)})
ref <- list()
fc_list <- function(fc) list(mean = as.numeric(fc$mean),
                             lo80 = as.numeric(fc$lower[,1]), hi80 = as.numeric(fc$upper[,1]),
                             lo95 = as.numeric(fc$lower[,2]), hi95 = as.numeric(fc$upper[,2]))
beer2 <- window(ausbeer, start = 1992, end = c(2007, 4))
ref$meanf_beer   <- fc_list(meanf(beer2, h = 10))
ref$naive_beer   <- fc_list(naive(beer2, h = 10))
ref$snaive_beer  <- fc_list(snaive(beer2, h = 10))
ref$drift_goog   <- fc_list(rwf(goog200, h = 40, drift = TRUE))
ref$naive_goog   <- fc_list(naive(goog200, h = 40))
ref$snaive_a10_lambda <- fc_list(snaive(a10, h = 24, lambda = 0))
ref$drift_lambda_elec <- fc_list(rwf(elec, h = 12, drift = TRUE, lambda = 0.3))
beer3 <- window(ausbeer, start = 2008)
acc <- function(fc, x) { a <- accuracy(fc, x); as.list(as.data.frame(a)) }
ref$acc_meanf  <- acc(meanf(beer2, h = 10), beer3)
ref$acc_naive  <- acc(rwf(beer2, h = 10), beer3)
ref$acc_snaive <- acc(snaive(beer2, h = 10), beer3)
ref$acc_drift_goog <- acc(rwf(goog200, h = 40, drift = TRUE), window(goog, start = 201, end = 240))
ref$lambda_elec <- BoxCox.lambda(elec)
ref$lambda_a10  <- BoxCox.lambda(a10)
ref$lambda_ausbeer <- BoxCox.lambda(ausbeer)
ref$lambda_usnetelec <- BoxCox.lambda(usnetelec)
e <- tsCV(goog200, rwf, drift = TRUE, h = 1)
ref$tscv_rmse_drift <- sqrt(mean(e^2, na.rm = TRUE))
e8 <- tsCV(goog200, naive, h = 8)
ref$tscv_naive_h8_mse <- as.numeric(colMeans(e8^2, na.rm = TRUE))
e50 <- tsCV(goog200, naive, h = 1, initial = 50)
ref$tscv_initial50 <- c(sum(!is.na(e50)), sqrt(mean(e50^2, na.rm = TRUE)))
ew30 <- tsCV(goog200, naive, h = 1, window = 30)
ref$tscv_window30 <- c(sum(!is.na(ew30)), sqrt(mean(ew30^2, na.rm = TRUE)))
lb <- Box.test(residuals(naive(goog200)), lag = 10, fitdf = 0, type = "Lj")
ref$ljung_naive_goog <- list(stat = unname(lb$statistic), p = lb$p.value)
dir.create("tests/reference", showWarnings = FALSE, recursive = TRUE)
write_json(ref, "tests/reference/core_reference.json", digits = 12, auto_unbox = TRUE, pretty = TRUE)
cat("wrote tests/reference/core_reference.json\n")
